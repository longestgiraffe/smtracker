class SegPackError(Exception):
    """A pack operation refused or failed; the message names the file, the address and the reason."""


class PackCancelled(SegPackError):
    """The user cancelled. What was downloaded is kept (``.partial``) and the next install continues it."""


# ------------------------------------------------------------------- the spec
def frozen() -> bool:
    return bool(getattr(sys, "frozen", False))


def platform_key() -> str | None:
    """``"win-amd64"``, ``"mac-arm64"``, or None where no pack is pinned (Linux, Intel Mac, 32-bit)."""
    import platform

    machine = platform.machine().lower()
    if sys.platform == "win32" and machine in ("amd64", "x86_64"):
        return "win-amd64"
    if sys.platform == "darwin" and machine == "arm64":
        return "mac-arm64"
    return None


def offered_here() -> bool:
    """Whether this run offers the pack: the packaged app does; a source run only when asked (it has its own pip)."""
    if os.environ.get(OFFER_ENV):
        return True
    return frozen() and platform_key() is not None


def flavours(platform: str | None = None, spec=None) -> list:
    """The flavours pinned for ``platform`` (default: this one), the recommended-first order is `recommend`'s."""
    spec = SPEC if spec is None else spec
    key = platform or platform_key()
    if key is None or key not in spec:
        raise SegPackError(f"no segmentation pack is pinned for this computer ({sys.platform}/"
                           f"{os.environ.get('PROCESSOR_ARCHITECTURE', 'unknown')}); only Windows (64-bit) and "
                           f"Apple-silicon Macs are.")
    return list(spec[key])


def wheels(flavour: str, platform: str | None = None, spec=None) -> list:
    """The pinned wheels of ``flavour``: dicts of name, version, filename, url, sha256, hash_from, size, installed."""
    spec = SPEC if spec is None else spec
    key = platform or platform_key()
    if key is None or key not in spec:
        flavours(platform, spec)                          # raises with the plain words
    if flavour not in spec[key]:
        raise SegPackError(f"there is no {flavour!r} pack for {key}; the choices are {', '.join(spec[key])}.")
    return list(spec[key][flavour])


def totals(flavour: str, platform: str | None = None, spec=None) -> tuple:
    """``(download bytes, installed bytes)`` of a whole pack."""
    chosen = wheels(flavour, platform, spec)
    return sum(w["size"] for w in chosen), sum(w["installed"] for w in chosen)


def check_spec(spec=None) -> list:
    """Problems with a spec, as sentences (empty when sound): every wheel has an https URL on an allowed host, a
    64-hex sha256, a size; no wheel is numpy, scipy or another package the bundle holds."""
    import re

    never = {"numpy", "scipy", "tifffile", "pillow", "pyside6", "shiboken6", "setuptools"}
    problems = []
    for key, by_flavour in (SPEC if spec is None else spec).items():
        for flavour, items in by_flavour.items():
            seen = set()
            for w in items:
                where = f"{key}/{flavour}/{w.get('filename', '?')}"
                if not re.fullmatch(r"[0-9a-f]{64}", str(w.get("sha256", ""))):
                    problems.append(f"{where}: no sha256")
                parts = urllib.parse.urlparse(str(w.get("url", "")))
                if parts.scheme != "https" or parts.netloc not in ALLOWED_HOSTS:
                    problems.append(f"{where}: URL {w.get('url')!r} is not https on {', '.join(ALLOWED_HOSTS)}")
                if not w.get("size") or not w.get("installed"):
                    problems.append(f"{where}: no size")
                name = re.sub(r"[-_.]+", "-", str(w.get("name", ""))).lower()
                if name in never:
                    problems.append(f"{where}: {name} is the bundle's, never the pack's")
                if name in seen:
                    problems.append(f"{where}: {name} twice")
                seen.add(name)
    return problems


def sizes_words(n: float) -> str:
    """Bytes in words: ``2.6 GB``, ``340 MB``."""
    n = float(n)
    if n >= 2**30:
        return f"{n / 2**30:.1f} GB"
    if n >= 2**20:
        return f"{n / 2**20:.0f} MB"
    return f"{n / 2**10:.0f} kB"


