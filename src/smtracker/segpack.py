@dataclass(frozen=True)
class PackProgress:
    """One tick: ``phase`` is ``download`` | ``verify`` | ``unpack`` | ``finish``; byte counts are of the whole pack
    (``done`` of ``total`` wheel bytes) and of the current file."""

    phase: str
    filename: str
    file_done: int
    file_total: int
    done: int
    total: int
    index: int
    count: int


def _state_path(part: Path) -> Path:
    return part / STATE


def _read_state(part: Path) -> dict:
    try:
        return json.loads(_state_path(part).read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}


def _write_state(part: Path, state: dict) -> None:
    tmp = _state_path(part).with_suffix(".tmp")
    tmp.write_text(json.dumps(state), encoding="utf-8")
    os.replace(tmp, _state_path(part))


def _check_url(w: dict) -> None:
    parts = urllib.parse.urlparse(w["url"])
    if _ALLOW_FILE_URLS and parts.scheme == "file":
        return
    if parts.scheme != "https" or parts.netloc not in ALLOWED_HOSTS:
        raise SegPackError(f"{w['filename']}: the address {w['url']} is not https on {', '.join(ALLOWED_HOSTS)}; "
                           f"refused")


def _sha256(path: Path, on_block=None) -> str:
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        while True:
            block = handle.read(1 << 20)
            if not block:
                break
            digest.update(block)
            if on_block is not None:
                on_block(len(block))
    return digest.hexdigest()


sha256_file = _sha256          # public name for the updater (`smtracker.updates`)


def _cancelled(cancel) -> bool:
    return bool(cancel is not None and (cancel.is_set() if hasattr(cancel, "is_set") else cancel()))


def fetch_file(url: str, target: Path, *, size: int, name: str, on_bytes=None, cancel=None, timeout: float = 60.0,
               user_agent: str = "SMTracker-segpack") -> None:
    """Fetch ``url`` into ``target``, resuming a ``.part`` left by an earlier try; the size must come out exactly.

    SHARED (27 Nov 2026): the pack's wheels and the updater's installer (`smtracker.updates`) come through this one
    downloader. It checks no address and no hash: the caller does both (`_check_url` here, the release's
    SHA256SUMS in the updater). ``on_bytes(done)`` is called after every block with the bytes held so far;
    ``cancel`` is an Event or a callable. Raises `PackCancelled` (what arrived is kept) or `SegPackError`."""
    part = target.with_name(target.name + ".part")
    have = part.stat().st_size if part.exists() else 0
    if have > size:
        part.unlink()
        have = 0
    request = urllib.request.Request(url, headers={"User-Agent": user_agent})
    if have:
        request.add_header("Range", f"bytes={have}-")
    try:
        with urllib.request.urlopen(request, timeout=timeout) as reply:               # verified TLS
            code = getattr(reply, "status", 200)
            if have and code != 206:
                have = 0                                                               # the server sent the whole file
            mode = "ab" if have else "wb"
            with open(part, mode) as out:
                done = have
                while True:
                    if _cancelled(cancel):
                        raise PackCancelled(f"cancelled during {name}; {sizes_words(done)} of it is kept "
                                            f"and the next try continues from there")
                    block = reply.read(1 << 20)
                    if not block:
                        break
                    out.write(block)
                    done += len(block)
                    if on_bytes is not None:
                        on_bytes(done)
    except PackCancelled:
        raise
    except (urllib.error.URLError, OSError, TimeoutError) as exc:
        raise SegPackError(f"{name} could not be downloaded from {url}: {type(exc).__name__}: {exc}. "
                           f"What arrived is kept; try again to continue. Check the internet connection and the "
                           f"free space on the drive of {target.parent}.") from exc
    got = part.stat().st_size
    if got != size:
        raise SegPackError(f"{name} from {url} stopped at {got} of {size} bytes. What arrived is "
                           f"kept; try again to continue.")
    os.replace(part, target)


def _download(w: dict, target: Path, *, base_done: int, total: int, index: int, count: int, on_progress, cancel,
              timeout: float = 60.0) -> None:
    """Fetch one wheel into ``target`` (resuming a ``.part``), checked against its sha256 and size afterwards."""
    _check_url(w)

    def on_bytes(done):
        if on_progress is not None:
            on_progress(PackProgress("download", w["filename"], done, w["size"], base_done + done, total,
                                     index, count))

    fetch_file(w["url"], target, size=w["size"], name=w["filename"], on_bytes=on_bytes, cancel=cancel,
               timeout=timeout)


def _check_hash(w: dict, path: Path, *, base_done: int, total: int, index: int, count: int, on_progress) -> None:
    seen = 0

    def tick(n):
        nonlocal seen
        seen += n
        if on_progress is not None:
            on_progress(PackProgress("verify", w["filename"], seen, w["size"], base_done + seen, total, index, count))

    digest = _sha256(path, tick)
    if digest != w["sha256"]:
        path.unlink()
        raise SegPackError(f"{w['filename']} (from {w['url']}) does not match its pinned sha256: expected "
                           f"{w['sha256']}, got {digest}. The file was deleted and nothing from it was used.")


def _unpack(w: dict, wheel_file: Path, lib: Path) -> list:
    """Unpack a verified wheel into ``lib``; returns ``[[relative path, size], ...]`` of what was written. Refuses a
    member that would land outside ``lib``. ``<x>.data/purelib|platlib`` go to the root; scripts and headers are skipped."""
    written = []
    root = lib.resolve()
    try:
        with zipfile.ZipFile(wheel_file) as z:
            for info in z.infolist():
                name = info.filename
                if name.endswith("/"):
                    continue
                parts = name.split("/")
                if parts[0].endswith(".data"):
                    if len(parts) > 2 and parts[1] in ("purelib", "platlib"):
                        name = "/".join(parts[2:])
                    else:
                        continue
                target = (lib / name).resolve()
                if root != target and root not in target.parents:
                    raise SegPackError(f"{w['filename']} holds {info.filename!r}, which would be written outside "
                                       f"{lib}; refused")
                target.parent.mkdir(parents=True, exist_ok=True)
                with z.open(info) as src, open(target, "wb") as dst:
                    shutil.copyfileobj(src, dst, 1 << 20)
                written.append([name, info.file_size])
    except zipfile.BadZipFile as exc:
        raise SegPackError(f"{w['filename']} is not a readable wheel ({exc}), although its sha256 matched") from exc
    except OSError as exc:
        raise SegPackError(f"{w['filename']} could not be unpacked into {lib}: {type(exc).__name__}: {exc}. Check the "
                           f"free space on that drive.") from exc
    return written


def _finish(folder: Path, part: Path, flavour: str, chosen: list, state: dict) -> None:
    """Write the manifest and rename ``<folder>.partial`` into place. The rename is the moment the pack exists."""
    manifest = {
        "pack_version": PACK_VERSION, "platform": platform_key(), "python": PYTHON_TAG, "flavour": flavour,
        "created": time.strftime("%Y-%m-%d %H:%M:%S"),
        "installed_bytes": sum(sz for w in state["done_wheels"] for _p, sz in w["files"]),
        "wheels": [{"name": w["name"], "version": w["version"], "filename": w["filename"], "sha256": w["sha256"],
                    "files": next(d["files"] for d in state["done_wheels"] if d["filename"] == w["filename"])}
                   for w in chosen],
    }
    (part / MANIFEST).write_text(json.dumps(manifest), encoding="utf-8")
    shutil.rmtree(part / WHEELS_DIR, ignore_errors=True)
    try:
        _state_path(part).unlink()
    except OSError:
        pass
    if folder.is_dir() and not any(folder.iterdir()):
        folder.rmdir()                                    # an empty folder the user made for it
    if folder.exists():
        raise SegPackError(f"{folder} appeared while installing; it was not replaced. Remove it, then install again.")
    os.replace(part, folder)


def _install(chosen: list, flavour: str, folder: Path, fetch, on_progress, cancel) -> Path:
    """Shared body: ``fetch(w, wheel_file, base_done, ...)`` puts each wheel on disk (download, or copy from a folder)."""
    folder = Path(folder)
    if status(folder).state == "installed":
        raise SegPackError(f"{folder} already holds the pack. Remove it first to install again.")
    if folder.exists() and any(folder.iterdir()):
        raise SegPackError(f"{folder} exists and is not an installed pack (status: {status(folder).state}). "
                           f"Remove it or pick another folder; nothing was changed.")
    total = sum(w["size"] for w in chosen)
    part = _partial(folder)
    wheel_dir, lib = part / WHEELS_DIR, part / LIB
    try:
        wheel_dir.mkdir(parents=True, exist_ok=True)
        lib.mkdir(parents=True, exist_ok=True)
    except OSError as exc:
        raise SegPackError(f"{part} cannot be made: {type(exc).__name__}: {exc}") from exc
    need = sum(w["installed"] for w in chosen) + max(w["size"] for w in chosen)
    state = _read_state(part)
    if state.get("flavour") != flavour or state.get("pack_version") != PACK_VERSION:
        shutil.rmtree(part, ignore_errors=True)           # another flavour or version: start clean
        wheel_dir.mkdir(parents=True, exist_ok=True)
        lib.mkdir(parents=True, exist_ok=True)
        state = {}
    state.setdefault("done_wheels", [])
    state["flavour"], state["pack_version"] = flavour, PACK_VERSION
    already = sum(w["installed"] for d in state["done_wheels"] for w in chosen if w["filename"] == d["filename"])
    free = free_bytes(part)
    if free + already < need:
        raise SegPackError(f"{part.parent} has {sizes_words(free)} free and this pack needs about "
                           f"{sizes_words(need - already)} more while it installs. Pick a folder on another drive.")
    base = 0
    for index, w in enumerate(chosen, 1):
        record = next((d for d in state["done_wheels"] if d["filename"] == w["filename"]), None)
        if record is not None:
            base += w["size"]
            if on_progress is not None:
                on_progress(PackProgress("unpack", w["filename"], w["size"], w["size"], base, total, index, len(chosen)))
            continue
        if _cancelled(cancel):
            raise PackCancelled("cancelled; what was downloaded is kept and the next install continues from there")
        wheel_file = wheel_dir / w["filename"]
        fetch(w, wheel_file, base_done=base, total=total, index=index, count=len(chosen))
        _check_hash(w, wheel_file, base_done=base, total=total, index=index, count=len(chosen), on_progress=on_progress)
        if on_progress is not None:
            on_progress(PackProgress("unpack", w["filename"], 0, w["size"], base, total, index, len(chosen)))
        files = _unpack(w, wheel_file, lib)
        wheel_file.unlink()
        state["done_wheels"].append({"filename": w["filename"], "files": files})
        _write_state(part, state)
        base += w["size"]
        if on_progress is not None:
            on_progress(PackProgress("unpack", w["filename"], w["size"], w["size"], base, total, index, len(chosen)))
    if on_progress is not None:
        on_progress(PackProgress("finish", "", total, total, total, total, len(chosen), len(chosen)))
    _finish(folder, part, flavour, chosen, state)
    return folder


def install(flavour: str, folder=None, on_progress=None, cancel=None, *, spec=None, platform: str | None = None) -> Path:
    """Download, verify and unpack the ``flavour`` pack into ``folder`` (default `default_folder`); returns the folder.

    ``on_progress(PackProgress)`` is called as bytes arrive; ``cancel`` is a ``threading.Event`` (or a callable returning
    true): the download stops, what arrived is KEPT, and `PackCancelled` is raised. Run it again to continue. Raises
    `SegPackError` naming the file, the address and the reason; the folder does not exist unless every wheel is in."""
    chosen = wheels(flavour, platform, spec)
    folder = Path(folder) if folder else default_folder(flavour)

    def fetch(w, wheel_file, **kw):
        if wheel_file.exists():
            return                                        # downloaded earlier, unpacking was cut: hash decides
        _download(w, wheel_file, on_progress=on_progress, cancel=cancel, **kw)

    return _install(chosen, flavour, folder, fetch, on_progress, cancel)


def install_from_files(files_folder, flavour: str, folder=None, on_progress=None, cancel=None, *, spec=None,
                       platform: str | None = None) -> Path:
    """The same pack from wheels already on disk (an offline lab): ``files_folder`` holds the pinned wheels under their
    own file names. Each is checked against the same sha256. A missing one is named with the address to fetch it from."""
    chosen = wheels(flavour, platform, spec)
    files_folder = Path(files_folder)
    if not files_folder.is_dir():
        raise SegPackError(f"{files_folder} is not a folder")
    missing = [w for w in chosen if not (files_folder / w["filename"]).is_file()]
    if missing:
        raise SegPackError(f"{files_folder} lacks {len(missing)} of the {len(chosen)} wheels the {flavour} pack needs: "
                           + "; ".join(f"{w['filename']} (from {w['url']})" for w in missing))
    folder = Path(folder) if folder else default_folder(flavour)

    def fetch(w, wheel_file, *, base_done, total, index, count):
        if wheel_file.exists():
            return
        part = wheel_file.with_name(wheel_file.name + ".part")
        try:
            shutil.copyfile(files_folder / w["filename"], part)
        except OSError as exc:
            raise SegPackError(f"{w['filename']} could not be copied from {files_folder}: {exc}") from exc
        os.replace(part, wheel_file)

    return _install(chosen, flavour, folder, fetch, on_progress, cancel)


def remove(folder) -> list:
    """Delete the pack at ``folder`` and any unfinished download beside it; forget it if it was the remembered one.
    Returns what was deleted. Refuses a folder that is neither (never deletes an arbitrary folder)."""
    folder = Path(folder)
    gone = []
    for path in (folder, _partial(folder)):
        if not path.exists():
            continue
        if not ((path / MANIFEST).is_file() or (path / STATE).is_file() or (path / LIB).is_dir()):
            raise SegPackError(f"{path} does not look like a segmentation pack (no {MANIFEST}, {STATE} or {LIB}); "
                               f"it was not deleted.")
        try:
            shutil.rmtree(path)
        except OSError as exc:
            raise SegPackError(f"{path} could not be removed: {type(exc).__name__}: {exc}. A program may be using "
                               f"files in it; close SMTracker's segmentation and try again.") from exc
        gone.append(path)
    pack = remembered_pack()
    if pack and Path(pack["folder"]) == folder:
        forget_pack()
    deactivate(folder)
    return gone


# ------------------------------------------------------------------- run time
def activate(folder) -> bool:
    """Make the pack's packages importable: APPEND its library folder to ``sys.path`` (so the bundle's own modules win;
    see the module head) and, on Windows, add ``torch/lib`` to the DLL search path. Idempotent. Refuses a pack that is not
    installed (names the state); returns True when it activated now, False when it already was."""
    folder = Path(folder)
    st = status(folder)
    if not st.ok:
        raise SegPackError(st.words())
    lib = str(folder / LIB)
    fresh = lib not in sys.path
    if fresh:
        sys.path.append(lib)
    dll = folder / LIB / "torch" / "lib"
    if os.name == "nt" and dll.is_dir() and str(dll) not in [getattr(h, "path", None) for h in _dll_handles]:
        handle = os.add_dll_directory(str(dll))
        handle.path = str(dll)                            # type: ignore[attr-defined]
        _dll_handles.append(handle)
    import importlib

    importlib.invalidate_caches()
    return fresh


def deactivate(folder) -> None:
    """Take the pack's folder off ``sys.path`` again (it stays imported if it already was; a restart ends that)."""
    lib = str(Path(folder) / LIB)
    while lib in sys.path:
        sys.path.remove(lib)


def remember_pack(folder, flavour: str) -> None:
    from .ui import theme

    theme.remember(SETTINGS_KEY, {"folder": str(folder), "flavour": flavour, "pack_version": PACK_VERSION})


def remembered_pack():
    """``{"folder", "flavour", "pack_version"}`` as saved in the user's settings, or None."""
    from .ui import theme

    value = theme.remembered(SETTINGS_KEY)
    return value if isinstance(value, dict) and value.get("folder") else None


def forget_pack() -> None:
    from .ui import theme

    theme.remember(SETTINGS_KEY, None)


def activate_remembered() -> PackStatus | None:
    """At start: put the remembered pack on ``sys.path`` if it is sound. Returns its status (None when none is remembered).
    A pack that is damaged or another version is NOT activated and is said with a warning, never silently."""
    pack = remembered_pack()
    if pack is None:
        return None
    folder = Path(pack["folder"])
    st = status(folder)
    if st.ok:
        activate(folder)
    else:
        import warnings

        warnings.warn(f"the segmentation pack remembered at {folder} is not usable: {st.words()}", stacklevel=2)
    return st
