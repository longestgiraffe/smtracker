"""THE SEGMENTATION PACK: PyTorch and Cellpose, downloaded on demand into a folder of the user's choosing.

RULED 26 Nov 2026 ("cuda and cellpose download on demand is the way to go. then we dont need a lite version, people just
can press no"): the frozen application is ONE build, without torch, Cellpose or any model. Whoever wants model
segmentation (Cellpose-SAM) or training presses a button, and this module fetches PyTorch (the CUDA build where an
NVIDIA GPU is present, else the CPU build; the user may override), Cellpose 4 and the packages the bundle lacks, from their
OFFICIAL hosts (download.pytorch.org, files.pythonhosted.org), at EXACT pinned versions, each file checked against its
sha256, unpacked into one folder. Anyone else presses No. Cellpose-SAM's weights keep downloading at first use
(`segmentation.backends.download_cpsam`). Omnipose is never bundled and never downloaded (non-commercial licence).

This AMENDS the 18 Oct `optional_deps` ruling ("the packaged build must simply work and is never offered" an install) for
this one pack, and only in this way: NEVER pip into the bundled runtime. A pinned, hash-checked set of wheels is unpacked
into a SEPARATE folder and put on ``sys.path`` at run time.

THE PINS are data (`segpack_spec.SPEC`, generated by ``scripts/make_segpack_spec.py`` from PyTorch's index and PyPI's
JSON API). Only what the frozen bundle LACKS is in it: torch, torchvision, cellpose, segment_anything and the runtime
dependencies a lite bundle leaves out. numpy, scipy, tifffile, pillow and everything else the bundle holds are NEVER in
the pack: `check_spec` refuses a spec that names one.

WHY THE BUNDLE'S OWN MODULES WIN. PyInstaller 6 serves the bundle's modules through a finder on ``sys._MEIPASS``, which is
an ordinary ``sys.path`` entry (the first after the stdlib's); ``PathFinder`` walks ``sys.path`` in order and stops at the
first hit. `activate` APPENDS the pack's folder, so it is consulted only for a name nothing before it has: torch, cellpose
and the rest. Were a name in both, the bundle's copy would be imported and the pack's ignored, which is the direction
wanted (the bundle was tested as a whole). Source runs append too, so a development environment's own packages win there.

AN INSTALL IS ATOMIC. Wheels download into ``<folder>.partial`` (each as ``<name>.part``, resumed from its size when the
connection is cut or the user cancels), are checked against the pinned sha256, unpacked ONE AT A TIME (so the disk holds
at most one wheel beside the unpacked tree), and only when every wheel is in, the manifest is written and the folder is
renamed into place. A half-done install is the ``.partial`` folder: it never counts as the pack (`status` says
"unfinished"), and running install again continues it.

HEADLESS and Qt-free: the dialog (`ui.outlines.pack_dialog`) and ``smtracker --segmentation-pack`` both call this.
Everything raises `SegPackError` naming the file, the address and the reason; nothing falls back silently.

Interfaces: `platform_key`, `flavours`, `wheels`, `totals`, `detect_gpu`, `recommend`, `default_folder`, `free_bytes`,
`status`, `verify`, `install`, `install_from_files`, `remove`, `activate`, `activate_remembered`, `remember_pack`.
"""
