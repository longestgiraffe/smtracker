@dataclass(frozen=True)
class GpuInfo:
    present: bool
    name: str = ""
    memory_mb: int = 0
    driver: str = ""
    note: str = ""

    @property
    def driver_number(self) -> float:
        try:
            return float(self.driver)
        except ValueError:
            return 0.0


def _nvidia_smi() -> str | None:
    found = shutil.which("nvidia-smi")
    if found:
        return found
    for candidate in (Path(os.environ.get("SystemRoot", r"C:\Windows")) / "System32" / "nvidia-smi.exe",
                      Path(os.environ.get("ProgramFiles", r"C:\Program Files")) / "NVIDIA Corporation" / "NVSMI"
                      / "nvidia-smi.exe"):
        if candidate.is_file():
            return str(candidate)
    return None


def detect_gpu() -> GpuInfo:
    """An NVIDIA GPU and its driver, asked of ``nvidia-smi`` (installed with the driver). Never raises: what could not be
    asked is said in ``note``. No NVIDIA GPU (or a Mac) is ``present=False``."""
    if sys.platform == "darwin":
        return GpuInfo(False, note="Apple silicon uses its own GPU (MPS) with the one pack built for it.")
    tool = _nvidia_smi()
    if tool is None:
        return GpuInfo(False, note="no NVIDIA driver was found (nvidia-smi is not installed).")
    try:
        out = subprocess.run(
            [tool, "--query-gpu=name,memory.total,driver_version", "--format=csv,noheader,nounits"],
            capture_output=True, text=True, timeout=15,
            creationflags=NO_WINDOW)
    except (OSError, subprocess.TimeoutExpired) as exc:
        return GpuInfo(False, note=f"nvidia-smi could not be run ({type(exc).__name__}: {exc}).")
    lines = [ln for ln in out.stdout.splitlines() if ln.strip()]
    if out.returncode != 0 or not lines:
        return GpuInfo(False, note=f"nvidia-smi answered no GPU (exit {out.returncode}: "
                                   f"{(out.stderr or out.stdout).strip()[:160]}).")
    name, memory, driver = [part.strip() for part in lines[0].split(",")[:3]]
    try:
        mb = int(float(memory))
    except ValueError:
        mb = 0
    return GpuInfo(True, name, mb, driver)


def recommend(gpu: GpuInfo | None = None) -> tuple:
    """``(flavour, reason)``: the CUDA build where an NVIDIA GPU with a recent enough driver is present, else the CPU
    build. On an Apple-silicon Mac the one build. The reason is a sentence for the dialog."""
    if sys.platform == "darwin":
        return "default", "This Mac's own GPU is used by the build made for it."
    gpu = detect_gpu() if gpu is None else gpu
    if not gpu.present:
        return "cpu", "No NVIDIA GPU was found, so the CPU build is the one to use. " + gpu.note
    memory = f"{gpu.memory_mb / 1024:.1f} GB" if gpu.memory_mb else "memory unknown"
    if gpu.driver_number and gpu.driver_number < MIN_CUDA_DRIVER:
        return "cpu", (f"{gpu.name} ({memory}) is present, but its driver ({gpu.driver}) is older than {MIN_CUDA_DRIVER:.0f}, "
                       f"which the CUDA build needs. Update the NVIDIA driver to use the GPU, or use the CPU build.")
    return "cuda", f"{gpu.name} ({memory}, driver {gpu.driver}) was found, so the CUDA build can use it."


def default_folder(flavour: str) -> Path:
    """Where a pack goes unless the user picks another: under the user's local app data, named for the pack's version
    and flavour (``segmentation-1-cuda``), so a later pack version sits beside this one."""
    if os.name == "nt" and os.environ.get("LOCALAPPDATA"):
        base = Path(os.environ["LOCALAPPDATA"]) / "SMTracker" / "packs"
    elif sys.platform == "darwin":
        base = Path.home() / "Library" / "Application Support" / "SMTracker" / "packs"
    else:
        base = Path(os.environ.get("XDG_DATA_HOME") or Path.home() / ".local" / "share") / "smtracker" / "packs"
    return base / pack_folder_name(flavour)


def fixed_drives() -> list:
    """Local fixed drives (Windows: C: and D: style roots); never a network, removable or optical drive. Empty elsewhere."""
    if os.name != "nt":
        return []
    import ctypes

    kernel = ctypes.WinDLL("kernel32", use_last_error=True)
    kernel.GetLogicalDrives.restype = ctypes.c_uint32
    kernel.GetDriveTypeW.argtypes = [ctypes.c_wchar_p]
    kernel.GetDriveTypeW.restype = ctypes.c_uint
    mask = kernel.GetLogicalDrives()
    out = []
    for i in range(26):
        if mask & (1 << i):
            root = f"{chr(65 + i)}:\\"
            if kernel.GetDriveTypeW(root) == 3:           # DRIVE_FIXED
                out.append(root)
    return out


def propose_folder(flavour: str, platform: str | None = None, spec=None, *, drives=None, free=None) -> tuple:
    """``(folder, sentence)``: the default folder when its drive has room (the install's need plus a 10 % margin), else a
    folder on the FIRST local fixed drive after it, in drive order, that has room (asked 26 Nov 2026: "if C is too
    small, u can use a folder in D"; the drive with the MOST room is often a data drive), with the reason in one plain
    line. The sentence is ``""`` when the default is kept. Where no fixed drive has room the default is kept and the
    sentence says so."""
    default = default_folder(flavour)
    need = int(needed_bytes(flavour, platform, spec) * 1.1)
    free = free or free_bytes
    have = free(default)
    if have >= need:
        return default, ""
    anchor = Path(default).anchor or str(default)
    best, best_free = None, have
    for root in sorted(fixed_drives() if drives is None else drives, key=lambda r: r.upper()):
        if root.upper() == anchor.upper():
            continue
        try:
            room = free(root)
        except OSError:
            continue
        if room >= need:
            best, best_free = root, room
            break
    if best is not None and best_free >= need:
        letter = anchor.rstrip(chr(92) + "/")
        return (Path(best) / "SMTracker" / "packs" / pack_folder_name(flavour),
                f"{letter} has {sizes_words(have)} free; the pack needs {sizes_words(need)}, so it goes on "
                f"{best.rstrip(chr(92) + '/')}.")
    return default, (f"{anchor.rstrip(chr(92) + '/')} has {sizes_words(have)} free and the pack needs "
                     f"{sizes_words(need)}; no local drive has room. Free some space or pick a folder.")


def pack_folder_name(flavour: str) -> str:
    return f"segmentation-{PACK_VERSION}-{flavour}"


def free_bytes(folder) -> int:
    """Free space on the drive ``folder`` would be made on (its nearest existing parent)."""
    path = Path(folder).expanduser().resolve() if not Path(folder).exists() else Path(folder).resolve()
    while not path.exists() and path != path.parent:
        path = path.parent
    return shutil.disk_usage(path).free


def needed_bytes(flavour: str, platform: str | None = None, spec=None) -> int:
    """What the drive must hold DURING an install: the unpacked tree plus the largest wheel (one is on disk at a time)."""
    chosen = wheels(flavour, platform, spec)
    return sum(w["installed"] for w in chosen) + max(w["size"] for w in chosen)


