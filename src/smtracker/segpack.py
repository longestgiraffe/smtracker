@dataclass
class PackStatus:
    """``state``: ``absent`` | ``unfinished`` | ``installed`` | ``damaged`` | ``other_version``."""

    state: str
    folder: Path
    flavour: str = ""
    version: str = ""
    installed_bytes: int = 0
    detail: str = ""
    packages: list = field(default_factory=list)

    @property
    def ok(self) -> bool:
        return self.state == "installed"

    def words(self) -> str:
        where = str(self.folder)
        if self.state == "installed":
            return (f"Installed in {where}: {self.flavour} build, pack version {self.version}, "
                    f"{sizes_words(self.installed_bytes)}.")
        if self.state == "unfinished":
            return f"An unfinished download is in {where}.partial ({self.detail}). Install continues it."
        if self.state == "damaged":
            return f"The pack in {where} is damaged: {self.detail}. Remove it and install again."
        if self.state == "other_version":
            return f"The pack in {where} is {self.detail}; this program needs pack version {PACK_VERSION}."
        return f"No segmentation pack in {where}."


def _partial(folder: Path) -> Path:
    return folder.with_name(folder.name + ".partial")


def _read_manifest(folder: Path):
    path = folder / MANIFEST
    if not path.is_file():
        return None
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        raise SegPackError(f"{path} cannot be read: {exc}") from exc
    if not isinstance(data, dict):
        raise SegPackError(f"{path} is not a pack manifest")
    return data


def status(folder, *, deep: bool = False) -> PackStatus:
    """What is at ``folder``. Quick by default (the manifest and the library folder); ``deep=True`` also checks every
    recorded file's presence and size (`verify`, a second or two for torch)."""
    folder = Path(folder)
    part = _partial(folder)
    if not folder.exists():
        if part.exists():
            done = _read_state(part).get("done_wheels", [])
            return PackStatus("unfinished", folder, detail=f"{len(done)} wheels unpacked so far")
        return PackStatus("absent", folder)
    try:
        manifest = _read_manifest(folder)
    except SegPackError as exc:
        return PackStatus("damaged", folder, detail=str(exc))
    if manifest is None:
        return PackStatus("damaged", folder, detail=f"it has no {MANIFEST} (an install that did not finish)")
    here = platform_key()
    if manifest.get("pack_version") != PACK_VERSION or manifest.get("platform") != here \
            or manifest.get("python") != PYTHON_TAG:
        return PackStatus("other_version", folder, str(manifest.get("flavour", "")), str(manifest.get("pack_version", "")),
                          detail=(f"pack version {manifest.get('pack_version')} for {manifest.get('platform')} "
                                  f"({manifest.get('python')})"))
    base = dict(flavour=str(manifest.get("flavour", "")), version=str(manifest.get("pack_version", "")),
                installed_bytes=int(manifest.get("installed_bytes", 0)),
                packages=[f"{w['name']} {w['version']}" for w in manifest.get("wheels", [])])
    if not (folder / LIB).is_dir():
        return PackStatus("damaged", folder, detail=f"its {LIB} folder is missing", **base)
    if deep:
        problems = verify(folder, manifest)
        if problems:
            return PackStatus("damaged", folder, detail=problems[0] + (f" (and {len(problems) - 1} more)"
                                                                       if len(problems) > 1 else ""), **base)
    return PackStatus("installed", folder, **base)


def verify(folder, manifest=None) -> list:
    """Problems found by checking every file the manifest lists exists with its recorded size (empty when sound)."""
    folder = Path(folder)
    manifest = manifest or _read_manifest(folder)
    if manifest is None:
        return [f"no {MANIFEST} in {folder}"]
    problems = []
    lib = folder / LIB
    for wheel in manifest.get("wheels", []):
        for rel, size in wheel.get("files", []):
            path = lib / rel
            try:
                actual = path.stat().st_size
            except OSError:
                problems.append(f"{wheel['name']}: {rel} is missing")
                continue
            if actual != size:
                problems.append(f"{wheel['name']}: {rel} is {actual} bytes, not {size}")
    return problems


